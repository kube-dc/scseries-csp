#!/usr/bin/env bash
# Print /etc/multipath/conf.d/sc-series.conf for the given Storage Center serial number(s).
#   hack/multipath-config.sh <ssn> [<ssn>...]   > /etc/multipath/conf.d/sc-series.conf
#
# 1) Finite queueing: the built-in hwtable entry for COMPELNT queues I/O forever on total path loss
#    (no_path_retry "queue"), which hangs pods, KubeVirt VMs and CSI unstage. 24 x polling_interval (5 s) =
#    ~2 min (enough for a controller failover), then I/O fails.
# 2) WWID exceptions, for node images that blacklist every WWID: SC volume NAAs are
#    6000d31 + <serial as 7 hex digits> + 00..., so the exception is ^36000d31<serial hex>00 per array.
#    vVol protocol endpoints ("Compellent Alu", 512 B) continue with 01... and stay excluded.
#    Verify on a node with:  multipath -v3 -d 2>&1 | grep -E 'whitelisted|blacklisted'
set -euo pipefail
[ $# -ge 1 ] || { sed -n '2,3p' "$0"; exit 2; }
cat <<'CONF'
# Dell SC Series (Compellent) - generated by scseries-csp hack/multipath-config.sh
devices {
	device {
		vendor "COMPELNT"
		product "Compellent Vol"
		no_path_retry 24
	}
}
blacklist_exceptions {
CONF
for ssn in "$@"; do
  [[ "$ssn" =~ ^[0-9]+$ ]] || { echo "serial must be numeric: $ssn" >&2; exit 2; }
  printf '\twwid "^36000d31%07x00"\t# Storage Center %s\n' "$ssn" "$ssn"
done
echo "}"
